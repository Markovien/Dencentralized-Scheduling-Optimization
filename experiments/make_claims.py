"""Generate ``CLAIMS.md`` — the evidence map required by ROADMAP.md §6.3 and check R-5.

Every claim in the manuscript must be one of exactly three things:

* **traceable** to a key in ``numbers.json`` produced by a recorded run,
* **proved** in the paper, with an explicit assumption list, or
* **attributed** to a cited source.

There is no fourth category, and this script makes that auditable rather than asserted. It
walks the manuscript, extracts every ``\\jnum`` key with the sentence it appears in, groups
them by the experiment block that produced them, and lists the formal results alongside the
test that would fail if each were false. Anything it cannot place is reported as a gap.

    python experiments/make_claims.py
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

JNUM = re.compile(r"\\jnum\{([^}]+)\}")
THEOREM = re.compile(
    r"\\begin\{(theorem|proposition)\}\[([^\]]*)\]\s*\n\s*\\label\{([^}]+)\}"
)

# Which test would fail if the result were false.  Kept here rather than in the manuscript
# because it is a property of the artefact, not of the paper.
FALSIFIERS = {
    "thm:t1": "tests/test_theory.py::test_t1_exact_potential_identity",
    "thm:t3": "tests/test_theory.py::test_t3_price_of_stability_is_one",
    "prop:n5": "tests/test_theory.py::test_n5_charger_congestion_makes_the_cost_supermodular",
    "prop:p5": "tests/test_theory.py::test_n5_relaxing_the_charger_restores_the_marginal_saving "
    "(empirical control; the proposition is stated conditionally and is not proved)",
    "thm:leastcore": "tests/test_theory.py::test_t5_least_core_is_correctly_signed_on_a_hand_computed_game "
    "and ::test_t5_least_core_detects_an_empty_core",
    "prop:t6": "tests/test_theory.py::test_t6_monotonicity_of_the_surrogate_is_measured_not_assumed",
    "prop:scale": "tests/test_cooperative.py::test_bargaining_is_invariant_under_affine_rescaling",
}

BLOCKS = {
    "e1.": "E1 — method comparison",
    "e2.": "E2 — where the exact model stops closing",
    "e3.": "E3 — cooperative stability",
    "e4.": "E4 — coalition structures",
    "e5.": "E5 — bargaining-derived weight",
    "e11.": "E11 — ablations",
    "e13.": "E13 — commensurability audit",
    "n5.": "N5 — the congestion counterexample",
    "units.": "Units contract (WP1)",
    "bench.": "Benchmark",
    "exp.": "Experimental design",
    "meta.": "Run metadata",
}


def sentence_of(text: str, index: int) -> str:
    """The sentence containing character ``index``, flattened to one line."""
    start = max(text.rfind(". ", 0, index), text.rfind("\n\n", 0, index)) + 1
    end = text.find(". ", index)
    end = len(text) if end == -1 else end + 1
    chunk = text[start:end]
    chunk = re.sub(r"\\jnum\{([^}]+)\}", r"<\1>", chunk)
    chunk = re.sub(r"\\(?:emph|textbf|textsc|texttt)\{([^}]*)\}", r"\1", chunk)
    chunk = re.sub(r"\\(?:ref|eqref|label|cite[tp]?)\*?\{[^}]*\}", "", chunk)
    chunk = re.sub(r"[\\{}]", "", chunk)
    return " ".join(chunk.split())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tex", type=Path, default=Path("paper_A/main.tex"))
    parser.add_argument("--numbers", type=Path, default=Path("results/numbers.json"))
    parser.add_argument("--out", type=Path, default=Path("paper_A/CLAIMS.md"))
    args = parser.parse_args(argv)

    text = args.tex.read_text()
    registry = json.loads(args.numbers.read_text()) if args.numbers.exists() else {}

    # --- numeric claims ------------------------------------------------------------------
    claims: dict[str, list[str]] = {}
    for match in JNUM.finditer(text):
        claims.setdefault(match.group(1), []).append(sentence_of(text, match.start()))

    lines: list[str] = [
        "# Evidence map",
        "",
        "Generated by `experiments/make_claims.py` — do not edit by hand.",
        "",
        "Every claim in the manuscript is one of three things: **traceable** to a key in",
        "`results/numbers.json` produced by a recorded run, **proved** in the paper with an",
        "explicit assumption list, or **attributed** to a cited source. This file is the",
        "audit of the first two.",
        "",
        f"- numeric claims: **{len(claims)}** distinct registry keys cited in the manuscript",
        f"- registry size: **{len(registry)}** keys recorded",
        f"- formal results: **{len(THEOREM.findall(text))}** stated",
        "",
        "## Formal results and their falsifying tests",
        "",
        "A result without a test that fails when the result is false is not delivered.",
        "",
        "| Result | Statement | Falsifying test |",
        "|---|---|---|",
    ]
    for kind, title, label in THEOREM.findall(text):
        test = FALSIFIERS.get(label, "**no falsifying test — gap**")
        lines.append(f"| `{label}` ({kind}) | {title} | `{test}` |")

    lines += [
        "",
        "## Numeric claims by experiment block",
        "",
        "Each key resolves to a value, unit and source recorded at run time. The sentence is",
        "the manuscript text the value appears in, with other keys shown as `<key>`.",
        "",
    ]

    unplaced: list[str] = []
    for prefix, title in BLOCKS.items():
        keys = sorted(k for k in claims if k.startswith(prefix))
        if not keys:
            continue
        lines += [f"### {title}", "", "| Key | Value | Unit | Used in |", "|---|---|---|---|"]
        for key in keys:
            entry = registry.get(key)
            if entry is None:
                unplaced.append(key)
                value, unit = "**MISSING**", ""
            else:
                raw = entry["value"]
                value = (
                    raw
                    if isinstance(raw, str)
                    else (str(raw) if isinstance(raw, int) else f"{raw:.{entry['precision']}f}")
                )
                unit = entry["unit"]
            sentence = claims[key][0]
            if len(sentence) > 150:
                sentence = sentence[:147] + "..."
            lines.append(f"| `{key}` | {value} | {unit} | {sentence} |")
        lines.append("")

    other = sorted(k for k in claims if not any(k.startswith(p) for p in BLOCKS))
    if other:
        lines += ["### Unclassified keys", ""] + [f"- `{k}`" for k in other] + [""]

    if unplaced:
        lines += [
            "## Gaps",
            "",
            "Keys cited in the manuscript with no registry entry. Each is a blocking defect:",
            "",
        ] + [f"- `{k}`" for k in sorted(set(unplaced))] + [""]
    else:
        lines += [
            "## Gaps",
            "",
            "None: every key cited in the manuscript resolves to a recorded value.",
            "",
        ]

    lines += [
        "## What is deliberately not claimed",
        "",
        "Stated here so the absences are auditable too, and matching the limitations section",
        "of the manuscript:",
        "",
        "- **No empirical price of anarchy.** The exact model closes too few instances of the",
        "  full problem, and its bounds on the rest are too weak to normalise against.",
        "- **No characterisation of the `c(S)` surrogate's gap** to the exact coalition",
        "  optimum, for the same reason. Two symptoms are measured instead: the surrogate's",
        "  monotonicity violation rate, and the instances on which it makes the grand",
        "  coalition lose to the reference policy.",
        "- **Proposition `prop:p5` is not proved.** The min-envelope step is open; it is",
        "  stated conditionally and nothing in the paper depends on it.",
        "- **No claim at industrial scale.** The benchmark is the classical four-machine",
        "  family, which is what makes exact cooperative certification affordable.",
        "",
    ]

    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out} — {len(claims)} claims, {len(unplaced)} gaps")
    return 1 if unplaced else 0


if __name__ == "__main__":
    raise SystemExit(main())
